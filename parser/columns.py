# Синонимы названий колонок базы (одно и то же может называться по-разному).
# Ключ — каноническое имя; значения — допустимые альтернативы. Сопоставление
# без учёта регистра. Нужны только для колонок, которые парсер реально читает
# (остальные — сквозные, выводятся под тем именем, что в базе).
PLANNING_COLUMN_ALIASES = {
    "Единый код": ["Код точки", "Код"],
    "Населенный пункт": ["Населённый пункт", "Город"],
    "Название улицы": ["Улица"],
    "Тип улицы": ["Тип"],
    "Номер дома": ["Дом"],
    "Станция метро": ["Метро"],
    "Цикличность": ["Сколько раз посещаем в месяц", "Периодичность", "Частота посещений"],
    "Код торгового представителя": ["Код ТП", "ТП", "Торговый представитель"],
}


def column_aliases(canonical: str) -> list[str]:
    """Каноническое имя колонки + все его синонимы."""
    return [canonical] + PLANNING_COLUMN_ALIASES.get(canonical, [])


def resolve_column(raw: dict, canonical: str):
    """Значение колонки по каноническому имени или синониму (без учёта регистра).

    Возвращает "" если колонки нет в словаре (и None -> "").
    """
    if not raw:
        return ""
    for alias in column_aliases(canonical):
        low = alias.lower()
        for k, v in raw.items():
            if str(k).strip().lower() == low:
                return "" if v is None else v
    return ""
